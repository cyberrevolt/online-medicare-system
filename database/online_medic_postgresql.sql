-- Online Medic PostgreSQL schema
-- Import this file into a NEW, EMPTY PostgreSQL database (PostgreSQL 16+).
-- It creates the tables and indexes and inserts required role rows.
-- It contains no demo accounts or passwords.

BEGIN;

CREATE TABLE IF NOT EXISTS roles (
  role_name VARCHAR(20) PRIMARY KEY CHECK (role_name IN ('PATIENT','DOCTOR','PHARMACIST','DELIVERY','ADMIN')),
  description VARCHAR(160) NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  phone VARCHAR(30),
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL REFERENCES roles(role_name),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS doctor_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  specialization VARCHAR(100) NOT NULL,
  qualification VARCHAR(160) NOT NULL,
  registration_number VARCHAR(80),
  experience_years INTEGER NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
  consultation_fee DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (consultation_fee >= 0),
  about VARCHAR(1200), clinic VARCHAR(180), rating DECIMAL(2,1) NOT NULL DEFAULT 0,
  consultation_type VARCHAR(40) NOT NULL DEFAULT 'Video', profile_image VARCHAR(500), demo_profile_key VARCHAR(80)
);
ALTER TABLE doctor_profiles ADD COLUMN IF NOT EXISTS demo_profile_key VARCHAR(80);
CREATE UNIQUE INDEX IF NOT EXISTS idx_doctor_profiles_demo_key ON doctor_profiles(demo_profile_key);
CREATE TABLE IF NOT EXISTS doctor_availability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES doctor_profiles(user_id) ON DELETE CASCADE,
  available_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
  UNIQUE (doctor_id, available_date, start_time), CHECK (end_time > start_time)
);
CREATE TABLE IF NOT EXISTS addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label VARCHAR(60) NOT NULL DEFAULT 'Home', line1 VARCHAR(220) NOT NULL,
  city VARCHAR(100) NOT NULL, state VARCHAR(100) NOT NULL, postal_code VARCHAR(20) NOT NULL,
  is_default BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL REFERENCES users(id), doctor_id BIGINT NOT NULL REFERENCES users(id),
  appointment_date DATE NOT NULL, start_time TIME NOT NULL, consultation_type VARCHAR(40) NOT NULL,
  fee DECIMAL(10,2) NOT NULL CHECK (fee >= 0), status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING','CONFIRMED','REJECTED','CANCELLED','COMPLETED','NO_SHOW')),
  payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING','SUCCESS','FAILED','REFUNDED','CANCELLED')), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS manufacturers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(140) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS medicines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES categories(id), manufacturer_id BIGINT REFERENCES manufacturers(id),
  name VARCHAR(180) NOT NULL, description VARCHAR(1200), price DECIMAL(10,2) NOT NULL CHECK (price >= 0),
  prescription_required BOOLEAN NOT NULL DEFAULT FALSE, image_url VARCHAR(500), active BOOLEAN NOT NULL DEFAULT TRUE,
  stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0), min_stock INTEGER NOT NULL DEFAULT 5 CHECK (min_stock >= 0)
);
CREATE TABLE IF NOT EXISTS medicine_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, medicine_id BIGINT NOT NULL REFERENCES medicines(id),
  batch_number VARCHAR(90) NOT NULL UNIQUE, manufacturing_date DATE, expiry_date DATE NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0), purchase_price DECIMAL(10,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS prescriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
  patient_id BIGINT NOT NULL REFERENCES users(id), doctor_id BIGINT NOT NULL REFERENCES users(id),
  clinical_notes VARCHAR(2000), status VARCHAR(20) NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('DRAFT','ISSUED','VERIFIED','REJECTED')),
  rejection_reason VARCHAR(500), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS prescription_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, prescription_id BIGINT NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
  medicine_name VARCHAR(180) NOT NULL, dosage VARCHAR(100) NOT NULL, frequency VARCHAR(100) NOT NULL,
  duration VARCHAR(100) NOT NULL, instructions VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, patient_id BIGINT NOT NULL REFERENCES users(id),
  address_id BIGINT REFERENCES addresses(id), total DECIMAL(10,2) NOT NULL CHECK (total >= 0), delivery_fee DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
  payment_method VARCHAR(40) NOT NULL, payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING','SUCCESS','FAILED','REFUNDED','CANCELLED')),
  status VARCHAR(30) NOT NULL DEFAULT 'PLACED' CHECK (status IN ('PLACED','CONFIRMED','PROCESSING','PACKED','SHIPPED','OUT_FOR_DELIVERY','DELIVERED','CANCELLED','RETURNED')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivery_fee DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0);
CREATE TABLE IF NOT EXISTS order_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status VARCHAR(40) NOT NULL, note VARCHAR(500), changed_by BIGINT REFERENCES users(id), changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_returns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
  patient_id BIGINT NOT NULL REFERENCES users(id), status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED'
    CHECK (status IN ('REQUESTED','APPROVED','REJECTED','RECEIVED','REFUNDED')),
  reason VARCHAR(500), requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_by BIGINT REFERENCES users(id), reviewed_at TIMESTAMP, review_note VARCHAR(500),
  image_required BOOLEAN NOT NULL DEFAULT FALSE, image_file VARCHAR(80), image_uploaded_at TIMESTAMP,
  pickup_staff_id BIGINT REFERENCES users(id), pickup_scheduled_at TIMESTAMP,
  pickup_status VARCHAR(20) NOT NULL DEFAULT 'NONE' CHECK (pickup_status IN ('NONE','SCHEDULED','PICKED_UP')),
  pickup_completed_at TIMESTAMP
);
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS review_note VARCHAR(500);
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS image_required BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS image_file VARCHAR(80);
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS image_uploaded_at TIMESTAMP;
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS pickup_staff_id BIGINT REFERENCES users(id);
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS pickup_scheduled_at TIMESTAMP;
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS pickup_status VARCHAR(20) NOT NULL DEFAULT 'NONE';
ALTER TABLE order_returns ADD COLUMN IF NOT EXISTS pickup_completed_at TIMESTAMP;
CREATE TABLE IF NOT EXISTS order_prescriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
  patient_id BIGINT NOT NULL REFERENCES users(id), file_name VARCHAR(80) NOT NULL, media_type VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','VERIFIED','REJECTED')),
  reviewed_by BIGINT REFERENCES users(id), review_note VARCHAR(500), uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  medicine_id BIGINT NOT NULL REFERENCES medicines(id), quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price DECIMAL(10,2) NOT NULL CHECK (unit_price >= 0)
);
CREATE TABLE IF NOT EXISTS order_item_batches (
  order_item_id BIGINT NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
  batch_id BIGINT NOT NULL REFERENCES medicine_batches(id), quantity INTEGER NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (order_item_id,batch_id)
);
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id), appointment_id BIGINT REFERENCES appointments(id), order_id BIGINT REFERENCES orders(id),
  amount DECIMAL(10,2) NOT NULL CHECK (amount >= 0), payment_method VARCHAR(40) NOT NULL,
  transaction_id VARCHAR(100) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','SUCCESS','FAILED','REFUNDED','CANCELLED')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS deliveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
  delivery_staff_id BIGINT REFERENCES users(id), status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  assigned_at TIMESTAMP, delivered_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
  patient_id BIGINT NOT NULL REFERENCES users(id), doctor_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id BIGINT NOT NULL REFERENCES users(id), message VARCHAR(4000) NOT NULL,
  sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, read_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
  patient_id BIGINT NOT NULL REFERENCES users(id), doctor_id BIGINT NOT NULL REFERENCES users(id),
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5), comment VARCHAR(1000), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(180) NOT NULL, body VARCHAR(1000) NOT NULL, read_at TIMESTAMP, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS inventory_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, medicine_id BIGINT NOT NULL REFERENCES medicines(id),
  quantity_change INTEGER NOT NULL, reason VARCHAR(180) NOT NULL, reference_id BIGINT, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS consultations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
  started_at TIMESTAMP, ended_at TIMESTAMP, meeting_link VARCHAR(500), status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
);
CREATE TABLE IF NOT EXISTS consultation_video_calls (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  started_by BIGINT NOT NULL REFERENCES users(id),
  status VARCHAR(20) NOT NULL DEFAULT 'RINGING' CHECK (status IN ('RINGING','ACTIVE','ENDED')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, accepted_at TIMESTAMP, ended_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_video_calls_appointment ON consultation_video_calls(appointment_id,id);
CREATE TABLE IF NOT EXISTS consultation_video_signals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  call_id BIGINT NOT NULL REFERENCES consultation_video_calls(id) ON DELETE CASCADE,
  sender_id BIGINT NOT NULL REFERENCES users(id), recipient_id BIGINT NOT NULL REFERENCES users(id),
  signal_type VARCHAR(12) NOT NULL CHECK (signal_type IN ('OFFER','ANSWER','ICE')),
  payload VARCHAR(20000) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_video_signals_inbox ON consultation_video_signals(call_id,recipient_id,id);
CREATE TABLE IF NOT EXISTS consultation_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, consultation_id BIGINT NOT NULL REFERENCES consultations(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES users(id), note VARCHAR(4000) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(160) NOT NULL UNIQUE, email VARCHAR(190), phone VARCHAR(30), active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS supplier_purchases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  medicine_id BIGINT NOT NULL REFERENCES medicines(id), batch_id BIGINT REFERENCES medicine_batches(id),
  quantity INTEGER NOT NULL CHECK (quantity > 0), unit_cost DECIMAL(10,2) NOT NULL CHECK (unit_cost >= 0),
  purchased_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS refunds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payment_id BIGINT NOT NULL REFERENCES payments(id),
  amount DECIMAL(10,2) NOT NULL CHECK (amount > 0), status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','PROCESSED')),
  reason VARCHAR(500), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  initiated_by BIGINT REFERENCES users(id), reviewed_by BIGINT REFERENCES users(id), reviewed_at TIMESTAMP,
  review_note VARCHAR(500), processed_by BIGINT REFERENCES users(id), processed_at TIMESTAMP
);
ALTER TABLE refunds ADD COLUMN IF NOT EXISTS initiated_by BIGINT REFERENCES users(id);
ALTER TABLE refunds ADD COLUMN IF NOT EXISTS reviewed_by BIGINT REFERENCES users(id);
ALTER TABLE refunds ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMP;
ALTER TABLE refunds ADD COLUMN IF NOT EXISTS review_note VARCHAR(500);
ALTER TABLE refunds ADD COLUMN IF NOT EXISTS processed_by BIGINT REFERENCES users(id);
ALTER TABLE refunds ADD COLUMN IF NOT EXISTS processed_at TIMESTAMP;
CREATE TABLE IF NOT EXISTS patient_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, date_of_birth DATE, gender VARCHAR(30), emergency_contact VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS pharmacist_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, license_number VARCHAR(100), pharmacy_name VARCHAR(180), profile_image VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS pharmacy_settings (
  id SMALLINT PRIMARY KEY CHECK (id = 1), pharmacy_name VARCHAR(180) NOT NULL,
  profile_image VARCHAR(500), updated_by BIGINT REFERENCES users(id), updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS delivery_staff_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, vehicle_number VARCHAR(40), active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS cart (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cart_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cart_id BIGINT NOT NULL REFERENCES cart(id) ON DELETE CASCADE,
  medicine_id BIGINT NOT NULL REFERENCES medicines(id), quantity INTEGER NOT NULL CHECK (quantity > 0), UNIQUE(cart_id,medicine_id)
);
CREATE TABLE IF NOT EXISTS doctor_specializations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, doctor_id BIGINT NOT NULL REFERENCES doctor_profiles(user_id) ON DELETE CASCADE,
  specialization VARCHAR(100) NOT NULL, UNIQUE(doctor_id,specialization)
);
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES users(id), action VARCHAR(180) NOT NULL,
  detail VARCHAR(1200), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_doctors_search ON doctor_profiles(specialization, experience_years, consultation_fee);
CREATE INDEX IF NOT EXISTS idx_medicines_name ON medicines(name);
CREATE INDEX IF NOT EXISTS idx_medicine_batches_expiry ON medicine_batches(medicine_id,expiry_date,quantity);
CREATE INDEX IF NOT EXISTS idx_order_item_batches_batch ON order_item_batches(batch_id);
CREATE INDEX IF NOT EXISTS idx_appointments_patient ON appointments(patient_id, appointment_date);
CREATE INDEX IF NOT EXISTS idx_appointments_doctor ON appointments(doctor_id, appointment_date);
CREATE INDEX IF NOT EXISTS idx_orders_patient ON orders(patient_id, created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, read_at);
ALTER TABLE doctor_profiles ADD COLUMN IF NOT EXISTS profile_image VARCHAR(500);
ALTER TABLE pharmacist_profiles ADD COLUMN IF NOT EXISTS profile_image VARCHAR(500);

INSERT INTO roles (role_name, description) VALUES
  ('PATIENT', 'Patient account'),
  ('DOCTOR', 'Licensed healthcare professional'),
  ('PHARMACIST', 'Pharmacy team member'),
  ('DELIVERY', 'Delivery staff member'),
  ('ADMIN', 'System administrator')
ON CONFLICT (role_name) DO NOTHING;

COMMIT;
